import { escapeHtml as e, pathOf } from '../util.js';
import { fmtMs, fmtKb, fmtCls } from '../checks/performance.js';
import { CHECKS } from '../checks/index.js';

// Inline styles only: email clients (Gmail, Outlook) drop most <style> rules.
const C = { text: '#1f2328', muted: '#656d76', border: '#d0d7de', bg: '#f6f8fa', red: '#cf222e', amber: '#9a6700', green: '#1a7f37', blue: '#0969da' };
const td = `padding:8px 10px;border-bottom:1px solid ${C.border};vertical-align:top;font-size:13px;`;
const th = `padding:8px 10px;border-bottom:2px solid ${C.border};text-align:left;font-size:12px;color:${C.muted};text-transform:uppercase;letter-spacing:.04em;`;

/**
 * Render the report. `maxRows` caps each table (used for the email body; the attached
 * file and the saved report are uncapped).
 */
export function renderHtml(report, ai, { maxRows = Infinity } = {}) {
  const date = new Date(report.generatedAt).toUTCString();
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Website QA report</title></head>
<body style="margin:0;padding:0;background:${C.bg};font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif;color:${C.text};">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:${C.bg};"><tr><td align="center" style="padding:24px 12px;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="max-width:760px;background:#fff;border:1px solid ${C.border};border-radius:8px;">
<tr><td style="padding:24px 24px 8px;">
  <div style="font-size:20px;font-weight:600;">Website QA report</div>
  <div style="font-size:13px;color:${C.muted};margin-top:4px;">${e(date)}</div>
</td></tr>
${aiBlock(ai)}
${report.sites.map((s) => siteBlock(s, maxRows)).join('')}
<tr><td style="padding:16px 24px 24px;font-size:12px;color:${C.muted};">Generated by Warden. Timings come from a headless browser on the machine that ran the check, so treat them as a trend, not what every visitor sees.</td></tr>
</table></td></tr></table></body></html>`;
}

function aiBlock(ai) {
  if (!ai?.text) return '';
  const lines = ai.text.split(/\r?\n/).filter((l) => l.trim());
  const body = lines
    .map((l) => (/^\s*[-*•]\s+/.test(l) ? `<div style="margin:4px 0 4px 12px;">• ${e(l.replace(/^\s*[-*•]\s+/, ''))}</div>` : `<div style="margin:6px 0;">${e(l)}</div>`))
    .join('');
  return `<tr><td style="padding:8px 24px;">
  <div style="background:#ddf4ff;border:1px solid #54aeff66;border-radius:6px;padding:14px 16px;font-size:14px;line-height:1.5;">
    <div style="font-size:12px;font-weight:600;color:${C.blue};text-transform:uppercase;letter-spacing:.04em;margin-bottom:6px;word-break:break-word;">AI summary · ${e(ai.provider)} / ${e(ai.model)}</div>
    ${body}
  </div></td></tr>`;
}

// Checks with their own layout. Any other check gets genericSection().
const SECTIONS = {
  links: (s, list, maxRows) =>
    section('Broken links', list, maxRows, ['Link', 'Problem', 'Found on'], (i) => [
      `<a href="${e(i.detail.url)}" style="color:${C.blue};word-break:break-all;">${e(shorten(i.detail.url))}</a>${newTag(i)}`,
      sev(i) + e(i.message),
      foundOn(i.detail.foundOn),
    ]),
  forms: (s, list, maxRows) => formsSection(s, maxRows),
  performance: (s, list, maxRows) =>
    section('Slow pages', list, maxRows, ['Page', 'Problem'], (i) => [pageLink(i.page) + newTag(i), sev(i) + e(i.message)], perfSummary(s.performance)),
  meta: (s, list, maxRows) => section('Meta & SEO', list, maxRows, ['Page', 'Problem'], (i) => [pageLink(i.page) + newTag(i), sev(i) + e(i.message)]),
};

function genericSection(title, list, maxRows) {
  return section(e(title), list, maxRows, ['Page', 'Problem'], (i) => {
    const on = i.siteWide && i.detail?.pages?.length > 1 ? i.detail.pages : null;
    const where = on ? `<div style="color:${C.muted};">${on.length} page${on.length === 1 ? '' : 's'}</div>${foundOn(on)}` : pageLink(i.page);
    return [where + newTag(i), sev(i) + e(i.message)];
  });
}

function siteBlock(s, maxRows) {
  const byCheck = (check) => s.issues.filter((i) => i.check === check);
  // Reports saved before checks were pluggable have no s.checks: show the original four sections.
  const ran = CHECKS.filter((c) => (s.checks ? s.checks[c.name] : SECTIONS[c.name]));
  const sections = ran.map((c) =>
    SECTIONS[c.name] ? SECTIONS[c.name](s, byCheck(c.name), maxRows) : genericSection(s.checks[c.name].title || c.title, byCheck(c.name), maxRows)
  );
  return `<tr><td style="padding:16px 24px 0;">
  <div style="font-size:17px;font-weight:600;border-top:1px solid ${C.border};padding-top:16px;"><a href="${e(s.url)}" style="color:${C.text};text-decoration:none;">${e(new URL(s.url).host)}</a></div>
  <div style="font-size:13px;color:${C.muted};margin:4px 0 12px;">${s.pagesCrawled} pages crawled · ${s.linksChecked} links checked</div>
  ${stats(s)}${s.counts.ignored ? `\n  <div style="font-size:12px;color:${C.muted};margin-top:8px;">${s.counts.ignored} issue${s.counts.ignored === 1 ? '' : 's'} ignored by config</div>` : ''}
</td></tr>
${sections.join('\n')}
${fixedSection(s, maxRows)}`;
}

function stats(s) {
  const cell = (label, value, color) =>
    `<td style="padding:10px 12px;border:1px solid ${C.border};border-radius:6px;text-align:center;width:20%;"><div style="font-size:22px;font-weight:600;color:${value ? color : C.muted};">${value}</div><div style="font-size:11px;color:${C.muted};text-transform:uppercase;letter-spacing:.04em;">${label}</div></td>`;
  const gap = '<td style="width:8px;"></td>';
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border-collapse:separate;"><tr>
    ${cell('Critical', s.counts.critical, C.red)}${gap}${cell('Warnings', s.counts.warning, C.amber)}${gap}${cell('New', s.counts.new, C.blue)}${gap}${cell('Fixed', s.fixed.length, C.green)}
  </tr></table>`;
}

function section(title, rows, maxRows, headers, toCells, preface = '') {
  const shown = rows.slice(0, maxRows);
  const more = rows.length - shown.length;
  const body = rows.length
    ? `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border-collapse:collapse;">
        <tr>${headers.map((h) => `<th style="${th}">${h}</th>`).join('')}</tr>
        ${shown.map((r) => `<tr>${toCells(r).map((c) => `<td style="${td}">${c}</td>`).join('')}</tr>`).join('')}
      </table>${more > 0 ? `<div style="font-size:12px;color:${C.muted};padding:6px 10px;">+ ${more} more in the attached full report</div>` : ''}`
    : `<div style="font-size:13px;color:${C.green};padding:4px 0;">✓ No problems found</div>`;
  return `<tr><td style="padding:16px 24px 0;">
  <div style="font-size:15px;font-weight:600;margin-bottom:6px;">${title} <span style="color:${C.muted};font-weight:400;">(${rows.length})</span></div>
  ${preface}${body}</td></tr>`;
}

function formsSection(s, maxRows) {
  const results = s.formResults;
  const tested = results.length
    ? `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border-collapse:collapse;">
        <tr><th style="${th}">Form</th><th style="${th}">Result</th></tr>
        ${results
          .map(
            (r) => `<tr><td style="${td}">${pageLink(r.page)}<div style="color:${C.muted};font-size:12px;">${e(r.selector)} · ${e(r.mode)}</div></td>
            <td style="${td}"><span style="font-weight:600;color:${r.passed ? C.green : C.red};">${r.passed ? 'PASS' : 'FAIL'}</span> ${e(r.reason)}</td></tr>`
          )
          .join('')}
      </table>`
    : `<div style="font-size:13px;color:${C.muted};">No forms configured for testing. Add them under "forms" in qa.config.json.</div>`;
  const untested = s.untestedForms.length
    ? `<div style="font-size:13px;color:${C.muted};margin-top:10px;">Forms found but not tested (${s.untestedForms.length}):</div>
       <ul style="margin:4px 0 0;padding-left:20px;font-size:13px;color:${C.muted};">${s.untestedForms
         .slice(0, maxRows)
         .map((f) => `<li>${e(f.method.toUpperCase())} → ${e(pathOf(f.action))} (${f.fieldCount} field${f.fieldCount === 1 ? '' : 's'}) on ${e(pathOf(f.page))}${f.alsoOn ? ` and ${f.alsoOn} other page${f.alsoOn === 1 ? '' : 's'}` : ''}${f.id ? ` · #${e(f.id)}` : ''}</li>`)
         .join('')}</ul>`
    : '';
  const failed = results.filter((r) => !r.passed).length;
  return `<tr><td style="padding:16px 24px 0;">
  <div style="font-size:15px;font-weight:600;margin-bottom:6px;">Forms <span style="color:${C.muted};font-weight:400;">(${results.length} tested${failed ? `, ${failed} failing` : ''})</span></div>
  ${tested}${untested}</td></tr>`;
}

function perfSummary(p) {
  if (!p || p.avgLoadMs == null) return '';
  const bits = [`avg load ${fmtMs(p.avgLoadMs)}`];
  if (p.avgLcpMs != null) bits.push(`avg LCP ${fmtMs(p.avgLcpMs)}`);
  if (p.avgTransferKb != null) bits.push(`avg weight ${fmtKb(p.avgTransferKb)}`);
  if (p.avgCls != null) bits.push(`avg CLS ${fmtCls(p.avgCls)}`);
  return `<div style="font-size:13px;color:${C.muted};margin-bottom:8px;">${bits.join(' · ')}</div>`;
}

function fixedSection(s, maxRows) {
  if (!s.fixed.length) return '';
  return `<tr><td style="padding:16px 24px 0;">
  <div style="font-size:15px;font-weight:600;margin-bottom:6px;color:${C.green};">Fixed since last run (${s.fixed.length})</div>
  <ul style="margin:0;padding-left:20px;font-size:13px;">${s.fixed
    .slice(0, maxRows)
    .map((f) => `<li>${e(pathOf(f.page))}: ${e(f.message)}</li>`)
    .join('')}</ul></td></tr>`;
}

const sev = (i) => `<span style="display:inline-block;width:8px;height:8px;border-radius:4px;background:${i.severity === 'critical' ? C.red : C.amber};margin-right:6px;"></span>`;
const newTag = (i) => (i.isNew ? ` <span style="font-size:11px;font-weight:600;color:${C.blue};border:1px solid ${C.blue};border-radius:10px;padding:0 6px;">NEW</span>` : '');
const pageLink = (url) => `<a href="${e(url)}" style="color:${C.blue};word-break:break-all;">${e(pathOf(url))}</a>`;
const shorten = (url) => (url.length > 80 ? url.slice(0, 77) + '…' : url);
const foundOn = (pages = []) =>
  pages.slice(0, 3).map(pageLink).join('<br>') + (pages.length > 3 ? `<br><span style="color:${C.muted};">+${pages.length - 3} more</span>` : '');
